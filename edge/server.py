"""OpthaEdge-DED inference service for the Raspberry Pi 4.

Wraps the shared pipeline (pipeline.py -> pi_infer.py, generated by the training
notebook, section 22) in a small FastAPI app, following the UI Deployment
Guide, section 3. Never resize or normalise anywhere else, or grades will be wrong.

Endpoints
  GET  /health        model, artifact digest, preprocessing version, camera state
  POST /predict       multipart "file" -> quality gate -> 5-grade prediction
  POST /capture       Pi camera still (through the 20D lens) -> same pipeline,
                      plus the captured JPEG so the platform can store it
  GET  /preview.mjpg  low-resolution live stream for aligning the 20D lens

Run (on the Pi):
  uvicorn server:app --host 127.0.0.1 --port 8001
"""
import base64
import hmac
import os
import threading
import time

import cv2
from fastapi import Depends, FastAPI, File, Form, Header, HTTPException, UploadFile
from fastapi.responses import StreamingResponse

import pipeline

MAX_UPLOAD_BYTES = int(os.environ.get("MAX_UPLOAD_BYTES", str(15 * 1024 * 1024)))
API_KEY = os.environ.get("INFERENCE_API_KEY", "").strip()
CAMERA_MODE = os.environ.get("CAMERA", "auto").lower()       # auto | on | off
CAMERA_FLIP = os.environ.get("CAMERA_FLIP", "none").lower()  # none | h | v | both (20D image is inverted)
PREVIEW_SIZE = (640, 480)

pipe = pipeline.from_env(runtime="edge")
sess = pipe.sess  # kept for test_parity.py

app = FastAPI(title="OpthaEdge inference", version="1.1.0")
@app.get("/")
async def root():
    return {
        "status": "ok",
        "message": "OpthaEdge inference API is running",
        "docs": "/docs",
        "version": "1.1.0"
    }


def require_key(x_inference_key: str = Header(default="")):
    """Shared secret between the platform server and the Pi. Enabled when set."""
    if API_KEY and not hmac.compare_digest(x_inference_key.encode(), API_KEY.encode()):
        raise HTTPException(401, "Invalid inference key")


# ---- camera (picamera2, optional) ------------------------------------------
class Camera:
    """One Picamera2 instance shared by the preview stream and still capture."""

    def __init__(self):
        self.lock = threading.Lock()
        self.cam = None
        self.error = None
        self.still_config = None
        if CAMERA_MODE == "off":
            self.error = "Camera disabled (CAMERA=off)"
            return
        try:
            from picamera2 import Picamera2  # sudo apt install python3-picamera2
            from libcamera import Transform

            transform = Transform(
                hflip=CAMERA_FLIP in ("h", "both"), vflip=CAMERA_FLIP in ("v", "both")
            )
            self.cam = Picamera2()
            self.preview_config = self.cam.create_preview_configuration(
                main={"size": PREVIEW_SIZE, "format": "RGB888"}, transform=transform
            )
            self.still_config = self.cam.create_still_configuration(
                main={"format": "RGB888"}, transform=transform
            )
            self.cam.configure(self.preview_config)
            self.cam.start()
            time.sleep(2)  # let exposure settle
        except Exception as exc:  # no camera, no picamera2, or not a Pi
            self.cam = None
            self.error = f"Camera unavailable: {type(exc).__name__}: {exc}"
            if CAMERA_MODE == "on":
                raise

    @property
    def available(self):
        return self.cam is not None

    def preview_jpeg(self):
        with self.lock:
            frame = self.cam.capture_array("main")
        # picamera2 "RGB888" arrays are BGR-ordered, which is what OpenCV expects.
        ok, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, 70])
        return buf.tobytes() if ok else None

    def capture_bgr(self):
        with self.lock:
            return self.cam.switch_mode_and_capture_array(self.still_config, "main")


camera = Camera()


# ---- routes -----------------------------------------------------------------
@app.get("/health")
def health():
    out = pipe.health({"available": camera.available, "detail": camera.error, "flip": CAMERA_FLIP})
    out["auth_required"] = bool(API_KEY)
    return out


@app.post("/predict", dependencies=[Depends(require_key)])
async def predict(file: UploadFile = File(...), include_preview: bool = Form(True)):
    try:
        bgr = pipeline.decode_image(await file.read(), MAX_UPLOAD_BYTES)
    except ValueError as exc:
        raise HTTPException(413 if "large" in str(exc) else 400, str(exc))
    return pipe.run(bgr, include_preview)


@app.post("/capture", dependencies=[Depends(require_key)])
def capture(include_preview: bool = Form(True)):
    if not camera.available:
        raise HTTPException(503, camera.error or "Camera unavailable")
    bgr = camera.capture_bgr()
    ok, buf = cv2.imencode(".jpg", bgr, [cv2.IMWRITE_JPEG_QUALITY, 95])
    if not ok:
        raise HTTPException(500, "Could not encode the captured image")
    result = pipe.run(bgr, include_preview)
    result["captured_jpeg"] = base64.b64encode(buf.tobytes()).decode()
    return result


@app.get("/preview.mjpg", dependencies=[Depends(require_key)])
def preview():
    if not camera.available:
        raise HTTPException(503, camera.error or "Camera unavailable")

    def frames():
        deadline = time.monotonic() + 120  # the client reconnects for longer sessions
        while time.monotonic() < deadline:
            jpeg = camera.preview_jpeg()
            if jpeg:
                yield b"--frame\r\nContent-Type: image/jpeg\r\n\r\n" + jpeg + b"\r\n"
            time.sleep(0.08)

    return StreamingResponse(frames(), media_type="multipart/x-mixed-replace; boundary=frame")
