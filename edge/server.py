"""OpthaEdge-DED inference service for the Raspberry Pi 4.

Wraps pi_infer.py (generated by the training notebook, section 22) in a small
FastAPI app, following the UI Deployment Guide, section 3. Preprocessing and
session code are reused from pi_infer unchanged; never resize or normalise
anywhere else, or grades will be wrong.

Endpoints
  GET  /health        model, artifact digest, preprocessing version, camera state
  POST /predict       multipart "file" -> quality gate -> 5-grade prediction
  POST /capture       Pi camera still (through the 20D lens) -> same pipeline,
                      plus the captured JPEG so the platform can store it
  GET  /preview.mjpg  low-resolution live stream for aligning the 20D lens

Run (on the Pi):
  uvicorn server:app --host 127.0.0.1 --port 8001
"""
import base64
import hashlib
import hmac
import os
import threading
import time

import cv2
import numpy as np
from fastapi import Depends, FastAPI, File, Form, Header, HTTPException, UploadFile
from fastapi.responses import StreamingResponse

import pi_infer

HERE = os.path.dirname(os.path.abspath(__file__))

MODEL = os.environ.get("MODEL_PATH", os.path.join(HERE, "models", "student_int8.onnx"))
THREADS = int(os.environ.get("THREADS", "4"))
MODEL_VERSION = "student-mnv3-litecbam-" + os.path.basename(MODEL)
PREPROC_VERSION = "stage1-roi-224-v1"
BLUR_MIN = float(os.environ.get("BLUR_MIN", "30"))           # calibrate on your own images
BRIGHT_RANGE = (
    float(os.environ.get("BRIGHT_MIN", "25")),
    float(os.environ.get("BRIGHT_MAX", "220")),
)
MAX_UPLOAD_BYTES = int(os.environ.get("MAX_UPLOAD_BYTES", str(15 * 1024 * 1024)))
API_KEY = os.environ.get("INFERENCE_API_KEY", "").strip()
CAMERA_MODE = os.environ.get("CAMERA", "auto").lower()       # auto | on | off
CAMERA_FLIP = os.environ.get("CAMERA_FLIP", "none").lower()  # none | h | v | both (20D image is inverted)
PREVIEW_SIZE = (640, 480)


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


ARTIFACT_SHA256 = _sha256(MODEL)
sess = pi_infer.load_session(MODEL, THREADS)
# Warm-up so the first clinical request is not slow (guide, section 9).
sess.run(None, {"input": np.zeros((1, 3, 224, 224), np.float32)})

app = FastAPI(title="OpthaEdge inference", version="1.0.0")


def require_key(x_inference_key: str = Header(default="")):
    """Shared secret between the platform server and the Pi. Enabled when set."""
    if API_KEY and not hmac.compare_digest(x_inference_key.encode(), API_KEY.encode()):
        raise HTTPException(401, "Invalid inference key")


# ---- camera (picamera2, optional) ------------------------------------------
class Camera:
    """One Picamera2 instance shared by the preview stream and still capture."""

    def __init__(self):
        self.lock = threading.Lock()
        self.cam = None
        self.error = None
        self.still_config = None
        if CAMERA_MODE == "off":
            self.error = "Camera disabled (CAMERA=off)"
            return
        try:
            from picamera2 import Picamera2  # sudo apt install python3-picamera2
            from libcamera import Transform

            transform = Transform(
                hflip=CAMERA_FLIP in ("h", "both"), vflip=CAMERA_FLIP in ("v", "both")
            )
            self.cam = Picamera2()
            self.preview_config = self.cam.create_preview_configuration(
                main={"size": PREVIEW_SIZE, "format": "RGB888"}, transform=transform
            )
            self.still_config = self.cam.create_still_configuration(
                main={"format": "RGB888"}, transform=transform
            )
            self.cam.configure(self.preview_config)
            self.cam.start()
            time.sleep(2)  # let exposure settle
        except Exception as exc:  # no camera, no picamera2, or not a Pi
            self.cam = None
            self.error = f"Camera unavailable: {type(exc).__name__}: {exc}"
            if CAMERA_MODE == "on":
                raise

    @property
    def available(self):
        return self.cam is not None

    def preview_jpeg(self):
        with self.lock:
            frame = self.cam.capture_array("main")
        # picamera2 "RGB888" arrays are BGR-ordered, which is what OpenCV expects.
        ok, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, 70])
        return buf.tobytes() if ok else None

    def capture_bgr(self):
        with self.lock:
            return self.cam.switch_mode_and_capture_array(self.still_config, "main")


camera = Camera()


# ---- pipeline ---------------------------------------------------------------
def quality(bgr):
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    sharp = float(cv2.Laplacian(gray, cv2.CV_64F).var())
    bright = float(gray.mean())
    reasons = []
    if sharp < BLUR_MIN:
        reasons.append("BLURRY")
    if bright < BRIGHT_RANGE[0]:
        reasons.append("TOO_DARK")
    if bright > BRIGHT_RANGE[1]:
        reasons.append("TOO_BRIGHT")
    return {
        "gradable": not reasons,
        "sharpness": round(sharp, 1),
        "brightness": round(bright, 1),
        "reasons": reasons,
        "thresholds": {"blur_min": BLUR_MIN, "brightness_range": list(BRIGHT_RANGE)},
    }


def model_input_png(x):
    """The exact 224x224 image the model saw, for clinician inspection."""
    rgb = (x[0].transpose(1, 2, 0) * 255.0).clip(0, 255).astype(np.uint8)
    ok, buf = cv2.imencode(".png", cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR))
    return base64.b64encode(buf.tobytes()).decode() if ok else None


def run_pipeline(bgr, include_preview=True):
    base = {
        "model_version": MODEL_VERSION,
        "model_file": os.path.basename(MODEL),
        "artifact_sha256": ARTIFACT_SHA256,
        "preprocessing_version": PREPROC_VERSION,
        "image_width": int(bgr.shape[1]),
        "image_height": int(bgr.shape[0]),
        "research_only": True,
    }
    q = quality(bgr)
    if not q["gradable"]:
        return {
            **base,
            "gradable": False,
            "quality": q,
            "message": "Image quality too low, please recapture.",
        }

    t0 = time.perf_counter()
    x = pi_infer.preprocess_array(bgr)
    t1 = time.perf_counter()
    grade, p = pi_infer.predict(sess, x)
    t2 = time.perf_counter()
    probs = [float(v) for v in p]
    return {
        **base,
        "gradable": True,
        "quality": q,
        "grade": grade,
        "label": pi_infer.CLASS_NAMES[grade],
        "confidence": probs[grade],
        "probabilities": dict(zip(pi_infer.CLASS_NAMES, probs)),
        "probability_vector": probs,
        "any_dr_probability": 1.0 - probs[0],          # DR / non-DR mode (grade >= 1)
        "referable_probability": sum(probs[2:]),        # moderate or worse
        "preprocess_ms": round((t1 - t0) * 1000, 1),
        "latency_ms": round((t2 - t1) * 1000, 1),
        "model_input_png": model_input_png(x) if include_preview else None,
    }


def decode(data):
    if not data:
        raise HTTPException(400, "Empty image")
    if len(data) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "Image too large")
    bgr = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)
    if bgr is None:
        raise HTTPException(400, "Not a valid image")
    return bgr


# ---- routes -----------------------------------------------------------------
@app.get("/health")
def health():
    return {
        "status": "ok",
        "model": MODEL_VERSION,
        "model_file": os.path.basename(MODEL),
        "artifact_sha256": ARTIFACT_SHA256,
        "preprocessing": PREPROC_VERSION,
        "labels": pi_infer.CLASS_NAMES,
        "threads": THREADS,
        "camera": {"available": camera.available, "detail": camera.error, "flip": CAMERA_FLIP},
        "auth_required": bool(API_KEY),
    }


@app.post("/predict", dependencies=[Depends(require_key)])
async def predict(file: UploadFile = File(...), include_preview: bool = Form(True)):
    bgr = decode(await file.read())
    return run_pipeline(bgr, include_preview)


@app.post("/capture", dependencies=[Depends(require_key)])
def capture(include_preview: bool = Form(True)):
    if not camera.available:
        raise HTTPException(503, camera.error or "Camera unavailable")
    bgr = camera.capture_bgr()
    ok, buf = cv2.imencode(".jpg", bgr, [cv2.IMWRITE_JPEG_QUALITY, 95])
    if not ok:
        raise HTTPException(500, "Could not encode the captured image")
    result = run_pipeline(bgr, include_preview)
    result["captured_jpeg"] = base64.b64encode(buf.tobytes()).decode()
    return result


@app.get("/preview.mjpg", dependencies=[Depends(require_key)])
def preview():
    if not camera.available:
        raise HTTPException(503, camera.error or "Camera unavailable")

    def frames():
        deadline = time.monotonic() + 120  # the client reconnects for longer sessions
        while time.monotonic() < deadline:
            jpeg = camera.preview_jpeg()
            if jpeg:
                yield b"--frame\r\nContent-Type: image/jpeg\r\n\r\n" + jpeg + b"\r\n"
            time.sleep(0.08)

    return StreamingResponse(frames(), media_type="multipart/x-mixed-replace; boundary=frame")
